// Writes the wins and moratoriums into wins.html as plain HTML, so the page has its
// content before any JavaScript runs.
//
//   node tools/build-wins-static.js          check only, prints what would change
//   node tools/build-wins-static.js --write  rewrite the block in wins.html
//
// Why. wins.html carries 134 stopped projects and 656 moratoriums, and every one of them
// was fetched from /data/wins.json at runtime and written into #w-out by script. To anything
// that does not execute JavaScript the page was a heading, a filter bar and an empty div:
// 64 words. Google executes JavaScript, but on a slower second pass, and most of the other
// crawlers that matter here do not execute it at all. This is the site's most distinctive
// asset and its most linkable one, so it should not depend on a fetch succeeding.
//
// How it stays safe. The block is written between two markers inside #w-out and nothing else
// in the file is touched. On load the existing script replaces the whole innerHTML of #w-out,
// so a visitor with JavaScript sees exactly what they saw before and the static rows are gone
// before they could interact with them. Re-run this whenever data/wins.json changes.
//
// What must not move. data/build-pages.js reads wins.html to lift the site chrome for every
// generated page: both <style> blocks, <header class="masthead"> to the first </nav></div>,
// <footer class="footer"> to </footer>, and everything between </footer> and </body> as the
// shared script. This writes inside <main> only, adds no style block and no script, and
// therefore cannot change what any generated page inherits.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const START = '<!-- wins:static:start  generated by tools/build-wins-static.js, do not edit by hand -->';
const END = '<!-- wins:static:end -->';

const M = ['January', 'February', 'March', 'April', 'May', 'June',
  'July', 'August', 'September', 'October', 'November', 'December'];
const LAB = { Denied: 'Denied', Withdrawn: 'Withdrawn', Court: 'Blocked in court' };
const LEVEL = {
  municipality: 'Town or city', county: 'County', state: 'State',
  tribal: 'Tribal nation', national: 'Country'
};

const esc = t => String(t == null ? '' : t)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// Same shape as fd() in wins.html, so the static rows read identically to the rendered ones.
function fd(d) {
  const m = /^(\d{4})(?:-(\d{2}))?(?:-(\d{2}))?$/.exec(d || '');
  if (!m) return d || '';
  if (m[3]) return M[+m[2] - 1] + ' ' + (+m[3]) + ', ' + m[1];
  if (m[2]) return M[+m[2] - 1] + ' ' + m[1];
  return m[1];
}

const TODAY = new Date().toISOString().slice(0, 10);

// The source link is the page's own promise: "Each entry links to the news story or record
// behind it." The rendered table keeps its source in the details drawer, which no crawler
// opens, so the static rows carry it inline.
function srcCell(url) {
  if (!url) return '<td></td>';
  let host = '';
  try { host = new URL(url).hostname.replace(/^www\./, ''); } catch (e) { host = 'source'; }
  return '<td><a class="w-src" href="' + esc(url) + '" rel="nofollow noopener" target="_blank">'
    + esc(host) + '</a></td>';
}

function groupBy(list, country, state) {
  const by = {};
  list.forEach(x => {
    const c = country(x) || 'United States';
    const s = state(x) || 'Other';
    (by[c] = by[c] || {});
    (by[c][s] = by[c][s] || []).push(x);
  });
  return by;
}

function countries(by) {
  return Object.keys(by).sort((a, b) =>
    a === 'United States' ? -1 : b === 'United States' ? 1 : a.localeCompare(b));
}

// Place and developer names link where the live table links them: the project page, the ban's
// place page (data/project-pages.json, data/moratorium-pages.json, written by build-pages).
const readJson = (f, d) => { try { return JSON.parse(fs.readFileSync(path.join(ROOT, f), 'utf8')); } catch (e) { return d; } };
const PAGES = readJson('data/project-pages.json', {});
const MPAGES = readJson('data/moratorium-pages.json', []);
let MORS = [];
function nameLink(url, text, out) {
  return url ? '<a href="' + esc(url) + '"' + (out ? ' rel="nofollow noopener" target="_blank"' : '') + '>' + esc(text) + '</a>' : esc(text);
}

function winsTable(rows) {
  const body = rows
    .slice()
    .sort((a, b) => String(b.date).localeCompare(String(a.date)))
    .map(x => '<tr>'
      + '<td class="pl">' + nameLink(PAGES[x.id] || x.src, x.place, !PAGES[x.id]) + (x.dev ? '<small>' + nameLink(PAGES[x.id], x.dev) + '</small>' : '') + '</td>'
      + '<td><span class="w-tag">' + esc(LAB[x.type] || x.type) + '</span> ' + esc(x.how) + '.</td>'
      + '<td class="nw">' + esc(fd(x.date) || 'Not reported') + '</td>'
      + '<td>' + esc(x.size || 'Not reported') + '</td>'
      + '<td>' + esc(x.inv || 'Not reported') + '</td>'
      + srcCell(x.src)
      + '</tr>').join('');
  return '<table class="w-tbl"><thead><tr><th>Place</th><th>What happened</th><th>Date</th>'
    + '<th>Size</th><th>Investment</th><th>Source</th></tr></thead><tbody>' + body + '</tbody></table>';
}

// The moratoriums are rendered as a compact list rather than a table. There are 499 of them
// against 134 wins, and a full six-cell table for each took the page from 58KB to 337KB, most
// of it markup that the script throws away a moment later. A sentence a place keeps every fact
// the table carried, stays readable without JavaScript, and costs a third as much.
function morList(rows) {
  const items = rows
    .slice()
    .sort((a, b) => (LEVEL[a.level] || '').localeCompare(LEVEL[b.level] || '')
      || String(a.name).localeCompare(String(b.name)))
    .map(x => {
      const ended = x.end && x.end < TODAY;
      const tag = x.status === 'Proposed' ? 'Proposed' : ended ? 'Ended' : x.type;
      const when = x.start
        ? ' from ' + esc(fd(x.start)) + (x.end ? ' to ' + esc(fd(x.end)) : '')
        : '';
      const lvl = LEVEL[x.level] ? ' (' + esc(LEVEL[x.level]) + ')' : '';
      const src = x.src
        ? ' <a href="' + esc(x.src) + '" rel="nofollow noopener" target="_blank">source</a>'
        : '';
      return '<li>' + nameLink(MPAGES[MORS.indexOf(x)], x.name) + lvl + ': ' + esc(tag) + when + '.' + src + '</li>';
    }).join('');
  return '<ul class="w-static-list">' + items + '</ul>';
}

function tree(by, tableFn) {
  return countries(by).map(c => {
    const states = Object.keys(by[c]).sort();
    const n = states.reduce((a, s) => a + by[c][s].length, 0);
    return '<details class="w-c" open><summary><span class="w-nm">' + esc(c)
      + '</span><span class="w-n">' + n + '</span></summary>'
      + states.map(s => '<details class="w-s" open><summary><span class="w-nm">' + esc(s)
        + '</span><span class="w-n">' + by[c][s].length + '</span></summary>'
        + tableFn(by[c][s]) + '</details>').join('')
      + '</details>';
  }).join('');
}

// The moratoriums are off by default. Rendered in full they are 499 records against 134 wins
// and take the page from 58KB to 268KB, four fifths of it reference rows that the script
// discards a moment later. The wins are the asset this page is known for and the only part
// carrying written prose, so they go in statically and the moratorium tab keeps working the
// way it always has, from the fetch. Pass --moratoriums to include them and see the cost.
function build(data, withMors) {
  const wins = data.wins || [];
  const mors = (data.moratoriums || []).filter(x =>
    x.status === 'In effect' && !(x.end && x.end < TODAY));

  const winTree = tree(groupBy(wins, x => x.country, x => x.state), winsTable);

  let out = START + '\n'
    + '<div class="w-static">\n'
    + '<h2 class="w-static-h">Projects stopped</h2>\n'
    + '<p class="w-static-note">' + wins.length
    + ' data center projects that residents stopped, by a vote, a withdrawal or a court. '
    + 'Sorted newest first within each state. '
    + mors.length + ' places also have a moratorium or ban in force; '
    + 'the moratorium tab on this page lists them.</p>\n'
    + winTree + '\n';

  if (withMors) {
    out += '<h2 class="w-static-h">Moratoriums and bans in effect</h2>\n'
      + '<p class="w-static-note">' + mors.length
      + ' places with a data center moratorium or ban currently in force.</p>\n'
      + tree(groupBy(mors, x => x.country, x => x.state), morList) + '\n';
  }

  return out + '</div>\n' + END;
}

const winsPath = path.join(ROOT, 'wins.html');
const html = fs.readFileSync(winsPath, 'utf8');
const data = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/wins.json'), 'utf8'));
MORS = data.moratoriums || [];
const block = build(data, process.argv.indexOf("--moratoriums") >= 0);

const a = html.indexOf(START);
const b = html.indexOf(END);
let out;

if (a >= 0 && b > a) {
  out = html.slice(0, a) + block + html.slice(b + END.length);
} else {
  const anchor = '<div class="w-tree" id="w-out">';
  const i = html.indexOf(anchor);
  if (i < 0) throw new Error('wins.html: could not find ' + anchor);
  const j = i + anchor.length;
  out = html.slice(0, j) + '\n' + block + '\n' + html.slice(j);
}

// Guards. If any of these fail the file is left alone: build-pages.js lifts the chrome out of
// wins.html by these exact landmarks and a generated site of 2,100 pages depends on them.
const checks = [
  ['two style blocks', s => (s.match(/<style>/g) || []).length === (html.match(/<style>/g) || []).length],
  ['header landmark', s => s.indexOf('<header class="masthead">') >= 0],
  ['header end', s => s.indexOf('</nav></div>', s.indexOf('<header class="masthead">')) >= 0],
  ['footer landmark', s => s.indexOf('<footer class="footer"') >= 0],
  ['nothing added after the footer', s =>
    s.slice(s.indexOf('</footer>') + 9, s.indexOf('</body>')).trim()
    === html.slice(html.indexOf('</footer>') + 9, html.indexOf('</body>')).trim()],
  ['w-out still present', s => s.indexOf('id="w-out"') >= 0]
];
const failed = checks.filter(c => !c[1](out)).map(c => c[0]);
if (failed.length) {
  console.error('REFUSING TO WRITE, these would break data/build-pages.js: ' + failed.join(', '));
  process.exit(1);
}

const kb = n => Math.round(n / 1024) + 'KB';
console.log('wins ' + (data.wins || []).length
  + ', moratoriums in effect ' + (data.moratoriums || []).filter(x =>
    x.status === 'In effect' && !(x.end && x.end < TODAY)).length);
console.log('wins.html ' + kb(html.length) + ' -> ' + kb(out.length)
  + '  (static block ' + kb(block.length) + ')');
console.log('all ' + checks.length + ' chrome guards pass');

if (process.argv.indexOf('--write') >= 0) {
  fs.writeFileSync(winsPath, out);
  console.log('written');
} else {
  console.log('check only, nothing written. pass --write to apply');
}
