# -*- coding: utf-8 -*-
"""Regenerate the corpus-wide status table from the lane files.

    python tools/log-progress.py

Writes data/place-report-status.md, which is GENERATED. Nobody hand-edits it, so nobody can
clobber anyone by writing it back from a stale copy.

Why it no longer writes into data/place-report-progress.md. That file is shared by every session,
and a table inside it that all eight lanes rewrite is the worst kind of contention: the row count
and the "N place pages carry researched reporting" counter change on every page anyone finishes,
so every lane rewrites the same line, and `git commit -- <path>` commits the working-tree file
exactly as the last writer left it. Lane c lost seven rows twice that way and lane b briefly
reverted lane c's restore one second after it landed. Nothing careful fixes that; the shared
mutable table had to go.

So: per-lane counts live in data/progress-lane-<letter>.md, each written by one session only.
This script reads the place-report JSON files and regenerates the corpus view from them.
"""
import io, json, os, re

LANES = 'abcdefghijklmnop'


def lane_of(filename):
    m = re.match(r'place-reports(?:-([a-z]))?\.json$', filename)
    return (m.group(1) or 'a') if m else None


def main():
    rows = []
    per_lane = {}
    for f in sorted(os.listdir('data')):
        lane = lane_of(f)
        if not lane:
            continue
        try:
            part = json.load(io.open(os.path.join('data', f), encoding='utf-8'))
        except Exception as e:
            print('  ! could not read %s: %s' % (f, e))
            continue
        for url, rep in part.items():
            paras = rep.get('paragraphs') or []
            if not paras:
                continue
            words = sum(len(p.split()) for p in paras)
            rows.append((url, words, len(paras), len(rep.get('sources') or []), lane))
            per_lane[lane] = per_lane.get(lane, 0) + 1

    rows.sort()
    total_words = sum(r[1] for r in rows)

    out = []
    out.append('# Place report status (generated)')
    out.append('')
    out.append('Regenerated by `python tools/log-progress.py` from every `data/place-reports*.json`.')
    out.append('**Do not hand-edit this file.** Per-lane notes belong in `data/progress-lane-<letter>.md`.')
    out.append('')
    out.append('**%d place pages carry researched reporting, %s words in total.**'
               % (len(rows), format(total_words, ',')))
    out.append('')
    out.append('| Lane | Pages |')
    out.append('|---|---|')
    for L in LANES:
        if L in per_lane:
            out.append('| %s | %d |' % (L, per_lane[L]))
    out.append('')
    out.append('| Page | Words | Paras | Sources | Lane |')
    out.append('|---|---|---|---|---|')
    out += ['| %s | %d | %d | %d | %s |' % r for r in rows]
    out.append('')

    io.open('data/place-report-status.md', 'w', encoding='utf-8').write('\n'.join(out))
    print('%d pages, %s words, written to data/place-report-status.md'
          % (len(rows), format(total_words, ',')))
    for L in LANES:
        if L in per_lane:
            print('   lane %s: %d' % (L, per_lane[L]))


if __name__ == '__main__':
    main()
